void Process_ADC_Data_Once(void)
{
  SignalAnalysisResult sig_result = Analyze_Signal_ZC(adc_buffer, SAMPLE_BUFFER_SIZE, SAMPLING_RATE_HZ, ADC_REF_VOLTAGE);
  char sig_output[128];
  int len = sprintf(sig_output, "[1s Collection] Freq: %.2f Hz, Vpp: %.3f V, Vmin: %.3f V, Vmax: %.3f V\r\n",
          sig_result.frequency, sig_result.vpp, sig_result.vmin, sig_result.vmax);
  HAL_UART_Transmit(&huart1, (uint8_t*)sig_output, len, HAL_MAX_DELAY);
}
